"""Diff the real schema against the desired one and produce migration SQL.

Nothing is guessed silently:

* columns and tables are matched by name only;
* a (gone, new) pair that looks alike becomes a *rename decision* with the
  evidence that made it look alike;
* every drop (table, column, constraint, index) and every type change that can
  lose data or fail is a *decision* too.

Decisions are answered by id (``answers``), interactively or by an agent.  The
generated ``up`` SQL is executed inside the caller's transaction and the result
is compared with the desired state; ``down`` is generated by running the engine
in reverse and is checked the same way.  The caller rolls everything back.
"""

import os
import re
import difflib
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple, Set, Any

from morm.schema.state import Column, Constraint, Index, Table, SchemaState, differences
from morm.schema.introspect import introspect, _quote as q


class EngineError(Exception):
    pass


@dataclass
class Decision:
    id: str
    kind: str                       # rename_table | drop_table | rename_column | drop_column | alter_type | drop_constraint | drop_index
    summary: str
    options: Dict[str, str]         # option -> what it does
    recommended: str
    evidence: Dict[str, Any] = field(default_factory=dict)
    choice: Optional[str] = None    # the answer used (None = open, recommended was used for the preview)

    def to_json(self):
        return {'id': self.id, 'kind': self.kind, 'summary': self.summary, 'options': self.options,
                'recommended': self.recommended, 'evidence': self.evidence, 'choice': self.choice}


@dataclass
class Plan:
    up: List[str] = field(default_factory=list)
    down: List[str] = field(default_factory=list)
    decisions: List[Decision] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)
    unmanaged_tables: List[str] = field(default_factory=list)

    @property
    def open_decisions(self) -> List[Decision]:
        return [d for d in self.decisions if d.choice is None]

    @property
    def empty(self) -> bool:
        return not self.up


# ---------------------------------------------------------------- helpers

_SEQ_RE = re.compile(r"nextval\('([^']+)'::regclass\)")
_SERIAL = {'integer': 'serial', 'bigint': 'bigserial', 'smallint': 'smallserial'}


def _seq_of(c: Column) -> Optional[str]:
    if c.default:
        m = _SEQ_RE.fullmatch(c.default)
        if m:
            return m.group(1).strip('"')
    return None


def _norm_default(c: Column) -> Optional[str]:
    if c.default is None:
        return None
    return _SEQ_RE.sub("nextval(SEQ)", c.default)


def _col_sql(table: str, c: Column, for_create=False) -> str:
    seq = _seq_of(c)
    if seq and c.type in _SERIAL and seq == f'{table}_{c.name}_seq' and not c.identity and not c.generated:
        s = f'{q(c.name)} {_SERIAL[c.type]}'
        return s + (' NOT NULL' if c.notnull else '')
    s = f'{q(c.name)} {c.type}'
    if c.generated:
        s += f' GENERATED ALWAYS AS ({c.default}) STORED'
    elif c.identity:
        s += ' GENERATED ALWAYS AS IDENTITY' if c.identity == 'a' else ' GENERATED BY DEFAULT AS IDENTITY'
    elif c.default is not None:
        s += f' DEFAULT {c.default}'
    if c.notnull and not c.identity:
        s += ' NOT NULL'
    return s


_INT_RANK = {'smallint': 1, 'integer': 2, 'bigint': 3}
_VARCHAR = re.compile(r'^character varying(?:\((\d+)\))?$')
_NUMERIC = re.compile(r'^numeric(?:\((\d+),(\d+)\))?$')


def is_widening(old: str, new: str) -> bool:
    """True when every value of ``old`` converts losslessly to ``new``."""
    if old == new:
        return True
    oa, na = old.endswith('[]'), new.endswith('[]')
    if oa != na:
        return False
    if oa:
        return is_widening(old[:-2], new[:-2])
    mo, mn = _VARCHAR.match(old), _VARCHAR.match(new)
    if mo and (mn or new == 'text'):
        if new == 'text' or mn.group(1) is None:
            return True
        return mo.group(1) is not None and int(mn.group(1)) >= int(mo.group(1))
    if old in _INT_RANK:
        if new in _INT_RANK:
            return _INT_RANK[new] >= _INT_RANK[old]
        if new == 'numeric':
            return True
    if old == 'real' and new == 'double precision':
        return True
    no, nn = _NUMERIC.match(old), _NUMERIC.match(new)
    if no and nn:
        if nn.group(1) is None:
            return True
        if no.group(1) is None:
            return False
        p0, s0, p1, s1 = int(no.group(1)), int(no.group(2)), int(nn.group(1)), int(nn.group(2))
        return s1 >= s0 and (p1 - s1) >= (p0 - s0)
    return False


def _name_similarity(a: str, b: str) -> float:
    return difflib.SequenceMatcher(None, a.lower(), b.lower()).ratio()


def column_pair_score(old: Column, new: Column) -> Tuple[float, Dict[str, Any]]:
    """How much ``new`` looks like ``old`` renamed (0..1), with the evidence."""
    ev: Dict[str, Any] = {
        'old': {'type': old.type, 'notnull': old.notnull, 'default': old.default, 'position': old.position},
        'new': {'type': new.type, 'notnull': new.notnull, 'default': new.default, 'position': new.position},
    }
    s = 0.0
    if old.type == new.type:
        s += 0.45
        ev['same_type'] = True
    else:
        ev['same_type'] = False
    if old.notnull == new.notnull:
        s += 0.1
    if _norm_default(old) == _norm_default(new):
        s += 0.1
    if old.position == new.position:
        s += 0.15
    elif abs(old.position - new.position) <= 1:
        s += 0.08
    sim = _name_similarity(old.name, new.name)
    ev['name_similarity'] = round(sim, 2)
    s += 0.2 * sim
    return round(s, 3), ev


def table_pair_score(old: Table, new: Table) -> float:
    a = {(c.name, c.type) for c in old.columns.values()}
    b = {(c.name, c.type) for c in new.columns.values()}
    if not a or not b:
        return 0.0
    return round(len(a & b) / len(a | b), 3)


TRIAL_LOCK_TIMEOUT = os.environ.get('MORM_TRIAL_LOCK_TIMEOUT', '3s')

RENAME_CANDIDATE = 0.45
RENAME_RECOMMEND = 0.7
TABLE_CANDIDATE = 0.5
TABLE_RECOMMEND = 0.8


# ---------------------------------------------------------------- engine

class _Ctx:
    def __init__(self, answers: Dict[str, str], using: Dict[str, str], auto: bool,
                 forced_table_renames: Dict[str, str], forced_col_renames: Dict[Tuple[str, str], str],
                 schema: str = 'public'):
        self.schema = schema
        self.answers = answers
        self.using = using
        self.auto = auto  # reverse mode (down): drops are implied, renames are forced
        self.forced_table_renames = forced_table_renames
        self.forced_col_renames = forced_col_renames
        self.decisions: List[Decision] = []
        self.notes: List[str] = []
        # what the forward plan did, used to build the reverse
        self.table_renames: Dict[str, str] = {}
        self.col_renames: Dict[Tuple[str, str], str] = {}   # (new_table, old_col) -> new_col

    def decide(self, d: Decision, auto_choice: Optional[str] = None) -> str:
        if self.auto:
            d.choice = auto_choice or d.recommended
            return d.choice
        self.decisions.append(d)
        a = self.answers.get(d.id)
        if a is not None:
            if a not in d.options:
                raise EngineError(f'Invalid answer {a!r} for {d.id}; options: {", ".join(d.options)}')
            d.choice = a
            return a
        return d.recommended


async def _evidence_has_data(con, table: str, col: str) -> Optional[bool]:
    try:
        return await con.fetchval(f'SELECT EXISTS (SELECT 1 FROM {q(table)} WHERE {q(col)} IS NOT NULL)')
    except Exception:
        return None


async def _evidence_rows(con, table: str) -> Optional[int]:
    try:
        return await con.fetchval(f'SELECT count(*) FROM (SELECT 1 FROM {q(table)} LIMIT 1000001) x')
    except Exception:
        return None


async def _sequences(con) -> Set[str]:
    rows = await con.fetch("SELECT relname FROM pg_class WHERE relkind = 'S' "
                           "AND relnamespace = current_schema()::regnamespace")
    return {r['relname'] for r in rows}


async def _phase_tables_columns(con, ctx: _Ctx, actual: SchemaState, desired: SchemaState,
                                drop_tables: Set[str]) -> Tuple[List[str], List[str]]:
    """Table and column changes.  Returns (sql, unmanaged tables)."""
    sql: List[str] = []
    seqs = await _sequences(con)
    new_t = [t for t in desired.tables if t not in actual.tables]
    gone_t = [t for t in actual.tables if t not in desired.tables]

    # table renames
    renamed: Dict[str, str] = {}  # old -> new
    if ctx.auto:
        for old, new in ctx.forced_table_renames.items():
            if old in gone_t and new in new_t:
                renamed[old] = new
    else:
        pairs = []
        for n in new_t:
            for o in gone_t:
                s = table_pair_score(actual.tables[o], desired.tables[n])
                if s >= TABLE_CANDIDATE:
                    pairs.append((s, o, n))
        used: Set[str] = set()
        for s, o, n in sorted(pairs, reverse=True):
            if o in used or n in used:
                continue
            used |= {o, n}
            d = Decision(id=f'table:{o}->{n}', kind='rename_table',
                         summary=f'table "{o}" is gone and "{n}" is new',
                         options={'rename': f'ALTER TABLE "{o}" RENAME TO "{n}" (keeps the data)',
                                  'create': f'create "{n}" as a new table; "{o}" is left as it is'},
                         recommended='rename' if s >= TABLE_RECOMMEND else 'create',
                         evidence={'column_overlap': s, 'old_rows': await _evidence_rows(con, o)})
            if ctx.decide(d) == 'rename':
                renamed[o] = n
    for o, n in renamed.items():
        sql.append(f'ALTER TABLE {q(o)} RENAME TO {q(n)};')
        for c in actual.tables[o].columns.values():
            s_old = _seq_of(c)
            if s_old and s_old == f'{o}_{c.name}_seq' and s_old in seqs:
                sql.append(f'ALTER SEQUENCE {q(s_old)} RENAME TO {q(f"{n}_{c.name}_seq")};')
        ctx.table_renames[o] = n

    # tables without a model
    unmanaged = []
    to_drop: List[str] = []
    for o in gone_t:
        if o in renamed:
            continue
        if ctx.auto:
            if o in drop_tables:
                to_drop.append(o)
            continue
        did = f'table:{o}'
        if did in ctx.answers:
            d = Decision(id=did, kind='drop_table', summary=f'table "{o}" has no model',
                         options={'drop': f'DROP TABLE "{o}" (data is lost)', 'keep': 'leave it alone'},
                         recommended='keep', evidence={'rows': await _evidence_rows(con, o)})
            if ctx.decide(d) == 'drop':
                to_drop.append(o)
                continue
        unmanaged.append(o)

    if to_drop:
        # FKs of surviving tables that point at a dropped table go first
        for t in actual.tables.values():
            if t.name in to_drop:
                continue
            for c in t.constraints.values():
                if c.kind == 'f' and _references(c.definition) in to_drop:
                    sql.append(f'ALTER TABLE {q(renamed.get(t.name, t.name))} DROP CONSTRAINT {q(c.name)};')
        sql.append('DROP TABLE ' + ', '.join(q(t) for t in to_drop) + ';')

    # new tables (constraints and indexes come in the next phase)
    for n in new_t:
        if n in renamed.values():
            continue
        t = desired.tables[n]
        cols = ',\n'.join('    ' + _col_sql(n, c, True) for c in t.column_list())
        sql.append(f'CREATE TABLE {q(n)} (\n{cols}\n);')

    # columns of existing (or renamed) tables
    for n, t_new in desired.tables.items():
        old_name = next((o for o, nn in renamed.items() if nn == n), n)
        if old_name not in actual.tables:
            continue
        t_old = actual.tables[old_name]
        gone = [c for c in t_old.columns if c not in t_new.columns]
        new = [c for c in t_new.columns if c not in t_old.columns]
        col_renames: Dict[str, str] = {}
        if ctx.auto:
            for (tt, oc), nc in ctx.forced_col_renames.items():
                if tt == n and oc in gone and nc in new:
                    col_renames[oc] = nc
        else:
            pairs = []
            for nc in new:
                for oc in gone:
                    s, ev = column_pair_score(t_old.columns[oc], t_new.columns[nc])
                    if s >= RENAME_CANDIDATE:
                        pairs.append((s, oc, nc, ev))
            used = set()
            for s, oc, nc, ev in sorted(pairs, key=lambda x: x[0], reverse=True):
                if oc in used or nc in used:
                    continue
                used |= {oc, nc}
                ev['score'] = s
                ev['old_has_data'] = await _evidence_has_data(con, old_name, oc)
                d = Decision(id=f'col:{n}.{oc}->{nc}', kind='rename_column',
                             summary=f'column "{n}.{oc}" is gone and "{n}.{nc}" is new',
                             options={'rename': f'RENAME "{oc}" TO "{nc}" (keeps the data)',
                                      'drop_add': f'DROP "{oc}" (data is lost) and ADD "{nc}"'},
                             recommended='rename' if s >= RENAME_RECOMMEND else 'drop_add',
                             evidence=ev)
                if ctx.decide(d) == 'rename':
                    col_renames[oc] = nc
        for oc, nc in col_renames.items():
            sql.append(f'ALTER TABLE {q(n)} RENAME COLUMN {q(oc)} TO {q(nc)};')
            s_old = _seq_of(t_old.columns[oc])
            if s_old in seqs and s_old in (f'{old_name}_{oc}_seq', f'{n}_{oc}_seq'):
                cur = f'{n}_{oc}_seq' if old_name != n else s_old
                sql.append(f'ALTER SEQUENCE {q(cur)} RENAME TO {q(f"{n}_{nc}_seq")};')
            ctx.col_renames[(n, oc)] = nc
        for oc in gone:
            if oc in col_renames:
                continue
            ev = {'old': {'type': t_old.columns[oc].type, 'notnull': t_old.columns[oc].notnull},
                  'old_has_data': None if ctx.auto else await _evidence_has_data(con, old_name, oc)}
            d = Decision(id=f'col:{n}.{oc}', kind='drop_column',
                         summary=f'column "{n}.{oc}" is not in the model',
                         options={'drop': f'DROP COLUMN "{oc}" (data is lost)'},
                         recommended='drop', evidence=ev)
            ctx.decide(d, 'drop')
            sql.append(f'ALTER TABLE {q(n)} DROP COLUMN {q(oc)};')
        for nc in new:
            if nc in col_renames.values():
                continue
            c = t_new.columns[nc]
            if c.notnull and c.default is None and not c.identity and not _seq_of(c) and not ctx.auto:
                rows = await _evidence_rows(con, old_name)
                if rows:
                    ctx.notes.append(f'"{n}.{nc}" is NOT NULL without a default and the table has rows; '
                                     'ADD COLUMN will fail. Add a default or fill it in a hook.')
            sql.append(f'ALTER TABLE {q(n)} ADD COLUMN {_col_sql(n, c)};')
        # changed definitions (same name, or renamed)
        for nc, c_new in t_new.columns.items():
            oc = next((o for o, x in col_renames.items() if x == nc), nc)
            if oc not in t_old.columns or (oc != nc and oc not in col_renames):
                continue
            c_old = t_old.columns[oc]
            sql.extend(_alter_column(ctx, n, c_old, c_new, seqs, old_name))
    return sql, unmanaged


def _alter_column(ctx: _Ctx, table: str, a: Column, b: Column, seqs: Set[str], old_table: str) -> List[str]:
    out: List[str] = []
    col = q(b.name)
    t = q(table)
    if (a.identity, a.generated) != (b.identity, b.generated):
        raise EngineError(f'{table}.{b.name}: changing identity/generated columns is not supported; '
                          'write that migration by hand (hooks.py)')
    # defaults are compared after the sequence renames that already happened
    a_def = a.default
    s_old = _seq_of(a)
    if s_old:
        a_def = _SEQ_RE.sub(lambda m: f"nextval('{_renamed_seq(m.group(1), table, old_table, a.name, b.name)}'::regclass)", a.default)
    type_changed = a.type != b.type
    if type_changed:
        using = f'{col}::{b.type}'
        if not is_widening(a.type, b.type):
            did = f'type:{table}.{b.name}'
            d = Decision(id=did, kind='alter_type',
                         summary=f'"{table}.{b.name}" type {a.type} -> {b.type} may lose data or fail',
                         options={'cast': f'ALTER TYPE ... USING {ctx.using.get(did, using)}'},
                         recommended='cast', evidence={'old_type': a.type, 'new_type': b.type})
            ctx.decide(d, 'cast')
            using = ctx.using.get(did, using)
        if a_def is not None:
            out.append(f'ALTER TABLE {t} ALTER COLUMN {col} DROP DEFAULT;')
            a_def = None
        out.append(f'ALTER TABLE {t} ALTER COLUMN {col} TYPE {b.type} USING {using};')
    if a_def != b.default:
        if b.default is None:
            out.append(f'ALTER TABLE {t} ALTER COLUMN {col} DROP DEFAULT;')
        else:
            s_new = _seq_of(b)
            if s_new and s_new not in seqs and s_new != _renamed_seq(s_old or '', table, old_table, a.name, b.name):
                out.append(f'CREATE SEQUENCE IF NOT EXISTS {q(s_new)} OWNED BY {t}.{col};')
            out.append(f'ALTER TABLE {t} ALTER COLUMN {col} SET DEFAULT {b.default};')
    if a.notnull != b.notnull:
        out.append(f'ALTER TABLE {t} ALTER COLUMN {col} {"SET" if b.notnull else "DROP"} NOT NULL;')
    return out


def _renamed_seq(seq: str, table: str, old_table: str, old_col: str, new_col: str) -> str:
    if seq in (f'{old_table}_{old_col}_seq', f'{table}_{old_col}_seq'):
        return f'{table}_{new_col}_seq'
    return seq


_REF_RE = re.compile(r'REFERENCES\s+(?:"((?:[^"]|"")+)"|([^\s(]+))\s*\(')


def _references(defn: str) -> Optional[str]:
    m = _REF_RE.search(defn)
    if not m:
        return None
    return m.group(1).replace('""', '"') if m.group(1) is not None else m.group(2)


def _strip_name(defn: str, name: str) -> str:
    return defn.replace(q(name), '"?"', 1)


async def _phase_constraints(con, ctx: _Ctx, mid: SchemaState, desired: SchemaState) -> List[str]:
    """Constraint and index changes, computed on the state after phase 1."""
    drops_fk: List[str] = []
    drops: List[str] = []
    renames: List[str] = []
    adds: List[str] = []
    adds_idx: List[str] = []
    adds_fk: List[str] = []
    for n, t_new in desired.tables.items():
        t_mid = mid.tables.get(n, Table(n))
        # constraints
        a, b = t_mid.constraints, t_new.constraints
        for name in sorted(set(a) & set(b)):
            if a[name].definition != b[name].definition:
                (drops_fk if a[name].kind == 'f' else drops).append(
                    f'ALTER TABLE {q(n)} DROP CONSTRAINT {q(name)};')
                (adds_fk if b[name].kind == 'f' else adds).append(
                    f'ALTER TABLE {q(n)} ADD CONSTRAINT {q(name)} {b[name].definition};')
        only_a = [x for x in a if x not in b]
        only_b = [x for x in b if x not in a]
        for x in list(only_a):
            match = next((y for y in only_b if b[y].kind == a[x].kind and b[y].definition == a[x].definition), None)
            if match:
                renames.append(f'ALTER TABLE {q(n)} RENAME CONSTRAINT {q(x)} TO {q(match)};')
                only_a.remove(x)
                only_b.remove(match)
        for x in only_a:
            d = Decision(id=f'con:{n}.{x}', kind='drop_constraint',
                         summary=f'constraint "{x}" on "{n}" is not in the model',
                         options={'drop': f'DROP CONSTRAINT "{x}" ({a[x].definition})'},
                         recommended='drop', evidence={'definition': a[x].definition})
            ctx.decide(d, 'drop')
            (drops_fk if a[x].kind == 'f' else drops).append(f'ALTER TABLE {q(n)} DROP CONSTRAINT {q(x)};')
        for y in only_b:
            (adds_fk if b[y].kind == 'f' else adds).append(
                f'ALTER TABLE {q(n)} ADD CONSTRAINT {q(y)} {b[y].definition};')
        # indexes
        ia, ib = t_mid.indexes, t_new.indexes
        for name in sorted(set(ia) & set(ib)):
            if ia[name].definition != ib[name].definition:
                drops.append(f'DROP INDEX {q(name)};')
                adds_idx.append(ib[name].definition + ';')
        only_a = [x for x in ia if x not in ib]
        only_b = [x for x in ib if x not in ia]
        for x in list(only_a):
            key = _strip_name(ia[x].definition, x)
            match = next((y for y in only_b if _strip_name(ib[y].definition, y) == key), None)
            if match:
                renames.append(f'ALTER INDEX {q(x)} RENAME TO {q(match)};')
                only_a.remove(x)
                only_b.remove(match)
        for x in only_a:
            d = Decision(id=f'idx:{n}.{x}', kind='drop_index',
                         summary=f'index "{x}" on "{n}" is not in the model',
                         options={'drop': f'DROP INDEX "{x}"'},
                         recommended='drop', evidence={'definition': ia[x].definition})
            ctx.decide(d, 'drop')
            drops.append(f'DROP INDEX {q(x)};')
        for y in only_b:
            adds_idx.append(ib[y].definition + ';')
    return drops_fk + drops + renames + adds + adds_idx + adds_fk


async def _run(con, stmts: List[str]):
    """Run statements in one round trip; on failure find the failing one."""
    if not stmts:
        return
    try:
        async with con.transaction():
            await con.execute('\n'.join(stmts))
        return
    except Exception:
        pass
    for s in stmts:
        try:
            await con.execute(s)
        except Exception as e:
            raise EngineError(f'{type(e).__name__}: {e}\n  while running: {s}') from e


async def _forward(con, actual: SchemaState, desired: SchemaState, ctx: _Ctx, drop_tables: Set[str] = set()):
    """Generate and execute the forward SQL.  Returns (sql, unmanaged)."""
    sql1, unmanaged = await _phase_tables_columns(con, ctx, actual, desired, drop_tables)
    await _run(con, sql1)
    mid = await introspect(con, ctx.schema)
    sql2 = await _phase_constraints(con, ctx, mid, desired)
    await _run(con, sql2)
    return sql1 + sql2, unmanaged


class _Rollback(Exception):
    def __init__(self, payload):
        self.payload = payload


def _orig_table(new_table: str, ctx: _Ctx) -> str:
    # in reverse, columns are renamed after the table is renamed back
    for o, n in ctx.table_renames.items():
        if n == new_table:
            return o
    return new_table


async def make_plan(con, desired: SchemaState, answers: Dict[str, str] = {},
                    using: Dict[str, str] = {}, schema: str = 'public') -> Plan:
    """Compute the migration from the current schema to ``desired``.

    The up SQL and then the down SQL are executed inside a savepoint, each one
    verified against its target state, and rolled back.
    """
    ctx_holder: Dict[str, Any] = {}
    actual = await introspect(con, schema)
    ctx = _Ctx(dict(answers), dict(using), False, {}, {}, schema)
    try:
        async with con.transaction():
            # the trial run takes the same locks as the real migration; never wait behind other work
            await con.execute("SELECT set_config('lock_timeout', $1, true)", TRIAL_LOCK_TIMEOUT)
            up, unmanaged = await _forward(con, actual, desired, ctx)
            after = await introspect(con, schema)
            diff = differences(after.subset(desired.tables), desired)
            if diff:
                raise EngineError('The generated migration does not reach the models:\n  ' + '\n  '.join(diff))
            down: List[str] = []
            if up:
                created = [t for t in desired.tables
                           if t not in actual.tables and t not in ctx.table_renames.values()]
                dropped = [t for t in actual.tables if t not in desired.tables
                           and t not in ctx.table_renames and t not in unmanaged]
                touched = (set(desired.tables) - set(created)) | set(ctx.table_renames) | set(dropped)
                touched -= set(ctx.table_renames.values())
                target = actual.subset(touched)
                rctx = _Ctx({}, {}, True, {n: o for o, n in ctx.table_renames.items()},
                            {(_orig_table(t, ctx), nc): oc for (t, oc), nc in ctx.col_renames.items()}, schema)
                current = after.subset(set(desired.tables))
                down, _ = await _forward(con, current, target, rctx, drop_tables=set(created))
                back = await introspect(con, schema)
                diff = differences(back.subset(touched | set(created)), target)
                if diff:
                    raise EngineError('The generated down migration does not restore the schema:\n  '
                                      + '\n  '.join(diff))
            ctx_holder['r'] = (up, down, unmanaged)
            raise _Rollback(None)
    except _Rollback:
        pass
    up, down, unmanaged = ctx_holder['r']
    unknown = set(answers) - {d.id for d in ctx.decisions} - {f'table:{t}' for t in actual.tables}
    if unknown:
        ctx.notes.append('Answers that matched no decision: ' + ', '.join(sorted(unknown)))
    return Plan(up=up, down=down, decisions=ctx.decisions, notes=ctx.notes, unmanaged_tables=unmanaged)
